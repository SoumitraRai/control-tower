// Tiny localStorage helpers. Every access is guarded: private windows and
// locked-down browsers can throw, and the app must still work without storage.
const PREFIX = 'ct:';

export function load(key, fallback) {
  try {
    const v = localStorage.getItem(PREFIX + key);
    return v == null ? fallback : JSON.parse(v);
  } catch {
    return fallback;
  }
}

export function save(key, value) {
  try {
    localStorage.setItem(PREFIX + key, JSON.stringify(value));
  } catch {
    /* ignore */
  }
}
